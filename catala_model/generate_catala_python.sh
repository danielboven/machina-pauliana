#!/usr/bin/env sh
# Build a self-contained Catala Python package for the neuro-symbolic model.
# clerk emits the runtime+stdlib and the compiled scope into two dirs, using the
# absolute import `from catala_runtime import *`
# Here both dirs go into one package and rewrite those imports to relative, so it
# imports with no sys.path/importlib tricks. Re-run when the .catala_en changes:
#     sh catala_model/generate_catala_python.sh
set -eu

TARGET="faillissementspauliana"                 # clerk target (see clerk.toml)
HERE="$(cd "$(dirname "$0")" && pwd)"           # catala_model/
OUT="$HERE/../neuro_symbolic_model/catala_generated"

# 1. Compile (regenerates _build/ and _targets/).
( cd "$HERE" && clerk build )

# 2. Flatten runtime+stdlib and the compiled scope into one fresh package.
rm -rf "$OUT" && mkdir -p "$OUT"
cp "$HERE/_build/libcatala/python/"*.py "$OUT/"
cp "$HERE/_targets/$TARGET/python/"*.py "$OUT/"

# 3. Rewrite the two absolute imports clerk emits into relative ones. Keep the
#    `dates.` qualifier (don't `from .dates import *`): its Date namedtuple would
#    otherwise collide with the Date class catala_runtime.py defines itself.
sed -i 's/^from catala_runtime import/from .catala_runtime import/' "$OUT/"*.py
sed -i 's/^import dates$/from . import dates/' "$OUT/catala_runtime.py"

# 4. Make it a typed package with an explicit __all__.
touch "$OUT/py.typed"
python3 - "$OUT" <<'PY'
import sys, pathlib
out = pathlib.Path(sys.argv[1])
mods = sorted(p.stem for p in out.glob("*.py") if p.stem != "__init__")
out.joinpath("__init__.py").write_text(
    "# Auto-generated by catala_model/generate_catala_python.sh -- do not edit.\n"
    "__all__ = [\n" + "".join(f"    {m!r},\n" for m in mods) + "]\n")
PY

rm -rf "$OUT/__pycache__"
echo "Wrote $OUT ($(ls "$OUT"/*.py | wc -l) modules)"
